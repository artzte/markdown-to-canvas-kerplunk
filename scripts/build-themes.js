const fs = require('fs');
const path = require('path');
const { THEMES_DIR, flattenThemeCss } = require('../src/themes.js');

async function buildThemesData() {
    const files = fs.readdirSync(THEMES_DIR).filter(f => f.endsWith('.css'));
    const themes = {};

    for (const file of files) {
        const themeName = path.basename(file, '.css');
        const rawCss = fs.readFileSync(path.join(THEMES_DIR, file), 'utf8');
        themes[themeName] = await flattenThemeCss(rawCss, file);
    }

    const outputPath = path.join(__dirname, '..', 'src', 'themes-data.js');
    const content = `// Auto-generated by scripts/build-themes.js
// Contains pre-flattened CSS for all kerplunk built-in themes.

module.exports = ${JSON.stringify(themes, null, 2)};
`;

    fs.writeFileSync(outputPath, content, 'utf8');
    console.log(`✅ Precompiled ${Object.keys(themes).length} themes into ${outputPath}`);
}

buildThemesData().catch(err => {
    console.error('❌ Failed to compile themes:', err);
    process.exit(1);
});
