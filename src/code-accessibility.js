const { execFileSync } = require('child_process');

let cachedHighlightArgs = null;

/**
 * Returns the appropriate pandoc CLI flags to disable syntax highlighting.
 * Pandoc >= 3.0 uses --syntax-highlighting=none
 * Pandoc < 3.0 uses --no-highlight
 */
function getPandocHighlightArgs() {
    if (cachedHighlightArgs) {
        return cachedHighlightArgs;
    }
    try {
        const help = execFileSync('pandoc', ['--help'], {
            encoding: 'utf8',
            stdio: ['pipe', 'pipe', 'pipe']
        });
        if (help.includes('--syntax-highlighting')) {
            cachedHighlightArgs = ['--syntax-highlighting=none'];
        } else {
            cachedHighlightArgs = ['--no-highlight'];
        }
    } catch {
        cachedHighlightArgs = ['--syntax-highlighting=none'];
    }
    return cachedHighlightArgs;
}

/**
 * Enhances code samples for Canvas LMS accessibility compliance (WCAG 2.1 AA / Section 508):
 * 1. Wraps code samples in a single, simple <pre> tag
 * 2. Removes empty line anchors and links to nowhere (<a href="#cb...">) generated by pandoc
 * 3. Strips nested wrappers (div.sourceCode, inner code tags, skylighting spans) so Juice inlines clean pre styles
 * 4. Preserves inline code snippets (<code>...</code>) outside of <pre> tags
 */
function enhanceCodeAccessibility(html) {
    if (!html || typeof html !== 'string') {
        return html;
    }

    if (!html.includes('<pre') && !html.includes('sourceCode')) {
        return html;
    }

    // Step 1: Unwrap pandoc sourceCode wrapper divs:
    // <div class="sourceCode" id="...">...</div> -> extract inner pre or content
    let result = html.replace(
        /<div\b[^>]*class="[^"]*\bsourceCode\b[^"]*"[^>]*>([\s\S]*?)<\/div>/gi,
        (match, inner) => {
            const preMatch = inner.match(/<pre\b[^>]*>([\s\S]*?)<\/pre>/i);
            const preInner = preMatch ? preMatch[1] : inner;
            return `<pre>${preInner}</pre>`;
        }
    );

    // Step 2: Unwrap <code> tags directly nested inside <pre> tags
    result = result.replace(/<pre\b[^>]*>\s*<code\b[^>]*>([\s\S]*?)<\/code>\s*<\/pre>/gi, (match, codeInner) => {
        return `<pre>${codeInner}</pre>`;
    });

    // Step 3: Clean up all <pre> blocks:
    // - Strip any <a> tags (empty anchors or links to nowhere)
    // - Strip all <span> tags (pandoc line numbers, syntax highlighting spans)
    // - Strip any remaining <code> tags inside <pre>
    // - Trim leading/trailing blank lines while preserving indentation and inner newlines
    // - Ensure <pre> is a clean, simple wrapper
    result = result.replace(/<pre\b[^>]*>([\s\S]*?)<\/pre>/gi, (match, preInner) => {
        let cleaned = preInner;

        // Remove empty <a> tags
        cleaned = cleaned.replace(/<a\b[^>]*>\s*<\/a>/gi, '');

        // Unwrap any <a> tags inside <pre> to remove links to nowhere
        cleaned = cleaned.replace(/<a\b[^>]*>([\s\S]*?)<\/a>/gi, '$1');

        // Strip any self-closing or malformed <a> tags
        cleaned = cleaned.replace(/<a\b[^>]*\/?>/gi, '');

        // Strip <span> tags inside pre (pandoc skylighting spans)
        cleaned = cleaned.replace(/<\/?span\b[^>]*>/gi, '');

        // Strip any residual <code> tags inside pre
        cleaned = cleaned.replace(/<\/?code\b[^>]*>/gi, '');

        // Trim leading and trailing empty lines while preserving indentation
        cleaned = cleaned.replace(/^\n+|\n+$/g, '');

        return `<pre>${cleaned}</pre>`;
    });

    return result;
}

module.exports = {
    enhanceCodeAccessibility,
    getPandocHighlightArgs
};
